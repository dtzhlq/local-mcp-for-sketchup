import assert from 'node:assert/strict';
import { environmentDefine, environmentUpdate, environmentActivate, normalizeEnvironmentSettings, styleLoad, styleActivate } from '../src/environment-operations.mjs';
import { ensureMaterial } from '../src/material-operations.mjs';
import { addScene, setRenderingOptions } from '../src/view-operations.mjs';

const model = { materials: {}, scenes: [] };
const indoor = environmentDefine(model, { name: 'Indoor', id: 'env-indoor', path: 'assets/indoor.HDR', rotation: 90, use_as_skydome: false });
assert.equal(indoor.id, 'env-indoor');
assert.equal(indoor.evidence, 'mock');
assert.equal(environmentActivate(model, { environment_ref: 'Indoor' }), 'env-indoor');
environmentUpdate(model, { environment_ref: 'env-indoor', reflection_exposure: 2, linked_sun_position: [0.2, -0.7] });
assert.deepEqual(indoor.linked_sun_position, [0.2, -0.7, 0]);
assert.throws(() => environmentDefine(model, { name: 'Other', id: 'env-indoor', path: '/tmp/a.exr' }), /already exists/);
assert.throws(() => environmentDefine(model, { name: 'Remote', path: 'https://example.com/a.hdr' }), /local asset/);
assert.throws(() => environmentDefine(model, { name: 'OpaqueURI', path: 'https:remote.hdr' }), /local asset/);
assert.throws(() => environmentDefine(model, { name: 'Wrong', path: '/tmp/a.png' }), /must use/);
assert.throws(() => environmentUpdate(model, { environment_ref: 'Indoor', path: '/tmp/new.exr' }), /cannot replace/);
assert.throws(() => environmentUpdate(model, { environment_ref: 'Missing', rotation: 1 }), /resolve uniquely/);
assert.throws(() => environmentActivate(model, {}), /requires environment_ref/);
assert.throws(() => normalizeEnvironmentSettings({ rotation: 361 }), /from 0 to 360/);
assert.throws(() => normalizeEnvironmentSettings({ linked_sun_position: [0, 0, 1] }), /must be 0/);
assert.throws(() => normalizeEnvironmentSettings({ reflection_exposure: Infinity }), /number/);
assert.throws(() => normalizeEnvironmentSettings({ skydome_exposure: 21 }), /from 0 to 20/);
assert.equal(environmentActivate(model, { environment_ref: null }), null);

styleLoad(model, { name: 'VerifiedPhotoreal', path: 'assets/photoreal.style' });
model.rendering_options = { RenderMode: 6 };
const captured = styleLoad(model, { name: 'CapturedDisplay', path: 'assets/base.style', capture_current_display: true });
assert.deepEqual(captured.rendering_options, { RenderMode: 6 });
model.rendering_options.RenderMode = 3;
styleActivate(model, { style_ref: 'CapturedDisplay' });
assert.equal(model.rendering_options.RenderMode, 6);
assert.throws(() => styleLoad(model, { name: 'RejectedDisplay', path: 'assets/base.style', capture_current_display: true, activate: false }), /requires activate/);
assert.equal(styleActivate(model, { style_ref: 'VerifiedPhotoreal' }), 'VerifiedPhotoreal');
assert.throws(() => styleLoad(model, { name: 'Bad', path: '/tmp/not-saved.skp' }), /must use/);
addScene(model, { name: 'Detail', environment_ref: 'Indoor', use_environment: false, style_ref: 'VerifiedPhotoreal' });
assert.equal(model.scenes[0].environment_ref, 'env-indoor');
assert.equal(model.scenes[0].use_environment, false);
assert.equal(model.scenes[0].style_ref, 'VerifiedPhotoreal');
assert.throws(() => addScene(model, { name: 'MissingEnvironment', environment_ref: 'missing' }), /resolve uniquely/);
assert.throws(() => addScene(model, { name: 'NullEnvironment', environment_ref: null }), /non-empty string/);
setRenderingOptions(model, { ambient_occlusion: true, ambient_occlusion_distance: 10, ambient_occlusion_intensity: 0.7, ambient_occlusion_color: '#443322', ambient_occlusion_multiplier: 1.2 });
assert.equal(model.rendering_options.ambient_occlusion, true);
assert.equal(model.rendering_options.ambient_occlusion_multiplier, 1.2);
ensureMaterial(model, { name: 'Surface', workflow: 'pbr_metallic_roughness', pbr: { normal_scale: 0, normal_enabled: false, roughness_enabled: true } });
assert.equal(model.materials.Surface.pbr.normal_scale, 0);
assert.equal(model.materials.Surface.pbr.normal_enabled, false);
assert.throws(() => ensureMaterial(model, { name: 'Invalid', workflow: 'classic', pbr: { roughness_factor: 0.5 } }), /cannot be combined/);
ensureMaterial(model, { name: 'Bundled', skm_path: 'assets/material.skm' });
assert.equal(model.materials.Bundled.color, undefined, 'native SKM must not receive an invented base color');
assert.equal(model.materials.Bundled.native_asset_state, 'unread_mock');
assert.throws(() => ensureMaterial(model, { name: 'Bundled', skm_path: 'assets/other.skm' }), /new material name/);
console.log('native appearance operation validation: passed (mock only; no SketchUp rendering claims)');
