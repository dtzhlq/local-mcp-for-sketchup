#!/usr/bin/env node

import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const booleanSourcePath = path.join(repoRoot, 'sketchup_plugin/local_mcp_for_sketchup/boolean_operations.rb');
const modelRevisionSourcePath = path.join(repoRoot, 'sketchup_plugin/local_mcp_for_sketchup/model_revision.rb');
const manifestPath = path.join(repoRoot, 'sketchup_plugin/local_mcp_for_sketchup/runtime_source_manifest.rb');
const write = process.argv.slice(2).includes('--write');

const [booleanSource, modelRevisionSource] = await Promise.all([
  fs.readFile(booleanSourcePath),
  fs.readFile(modelRevisionSourcePath)
]);
const booleanSha256 = sha256(booleanSource);
const modelRevisionSha256 = sha256(modelRevisionSource);
const rendered = renderManifest({ booleanSha256, modelRevisionSha256 });

if (write) {
  await fs.writeFile(manifestPath, rendered, 'utf8');
  process.stdout.write(`${JSON.stringify({
    ok: true,
    written: true,
    boolean_operations_sha256: booleanSha256,
    model_revision_source_sha256: modelRevisionSha256
  }, null, 2)}\n`);
} else {
  const current = await fs.readFile(manifestPath, 'utf8').catch(() => null);
  if (current !== rendered) {
    process.stderr.write('Runtime source manifest is stale. Run this script with --write and review the generated file.\n');
    process.exitCode = 1;
  } else {
    process.stdout.write(`${JSON.stringify({
      ok: true,
      written: false,
      boolean_operations_sha256: booleanSha256,
      model_revision_source_sha256: modelRevisionSha256
    }, null, 2)}\n`);
  }
}

function sha256(buffer) {
  return crypto.createHash('sha256').update(buffer).digest('hex');
}

function renderManifest({ booleanSha256, modelRevisionSha256 }) {
  return `# frozen_string_literal: true

# Generated by scripts/generate-plugin-runtime-source-manifest.mjs.
# Run that generator after changing an attested source file, then review and
# commit the source and manifest together.
module LocalMcpForSketchUp
  module RuntimeSourceManifest
    BOOLEAN_OPERATIONS_RELATIVE_PATH = 'boolean_operations.rb'
    BOOLEAN_OPERATIONS_SHA256 = '${booleanSha256}'
    MODEL_REVISION_RELATIVE_PATH = 'model_revision.rb'
    MODEL_REVISION_SHA256 = '${modelRevisionSha256}'
  end
end
`;
}
