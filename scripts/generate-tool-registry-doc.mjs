#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { AGENT_GATEWAY_TOOL_NAMES, EXPERT_TOOL_NAMES, SESSION_CONTRACT_TOOL_NAMES, TOOL_REGISTRY, getToolEffect } from '../src/tool-registry.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(repoRoot, 'docs', 'tool-registry.md');
const expected = renderToolRegistryMarkdown(TOOL_REGISTRY, EXPERT_TOOL_NAMES, AGENT_GATEWAY_TOOL_NAMES, SESSION_CONTRACT_TOOL_NAMES);
const check = process.argv.includes('--check');

if (check) {
  const actual = await fs.readFile(outputPath, 'utf8').catch(() => '');
  if (actual !== expected) {
    throw new Error('docs/tool-registry.md is out of date. Run npm run tool-registry:sync.');
  }
  process.stdout.write(`${JSON.stringify({ ok: true, checked: path.relative(repoRoot, outputPath), tools: TOOL_REGISTRY.length }, null, 2)}\n`);
} else {
  await fs.writeFile(outputPath, expected, 'utf8');
  process.stdout.write(`${JSON.stringify({ ok: true, written: path.relative(repoRoot, outputPath), tools: TOOL_REGISTRY.length }, null, 2)}\n`);
}

function renderToolRegistryMarkdown(tools, expertToolNames, gatewayToolNames, sessionContractToolNames) {
  const rows = tools.map((tool, index) => `| ${index + 1} | \`${tool.name}\` | \`${getToolEffect(tool.name).effect}\` | ${escapeCell(tool.description)} |`);
  return [
    '# MCP Tool Registry',
    '',
    '> Generated by `npm run tool-registry:sync` from the shared stdio/HTTP tool registry. Do not edit this table by hand.',
    '',
    `Current tool count: **${tools.length}** (**${expertToolNames.length}** retained expert tools + **${gatewayToolNames.length}** Agent Gateway tools + **${sessionContractToolNames.length}** Session Contract tool). This is not the safe JSON DSL operation count and does not claim complete SketchUp API coverage.`,
    '',
    'The effect class is also consumed by HTTP timeout handling. New tools default fail-closed to `persistent_or_unknown` until explicitly classified as `none`.',
    '',
    '| # | Tool | Effect class | Contract summary |',
    '|---:|---|---|---|',
    ...rows,
    ''
  ].join('\n');
}

function escapeCell(value) {
  return String(value || '').replaceAll('|', '\\|').replaceAll('\n', ' ');
}
